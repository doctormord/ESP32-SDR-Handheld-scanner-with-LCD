#!/usr/bin/env python3
"""Generate main/boards/common/aafont.h: anti-aliased fonts for the survey UI,
4-bit alpha, from Aileron Regular (Sora Sagano, CC0), the font Pillow
bundles (ImageFont.load_default).

  UI_SCALE 1 (T-Display): big digits only; text stays the 5x7 bitmap font.
  UI_SCALE 2 (JC3248):    text at two sizes (the 5x7 font's scale 1 and 2)
                          and big digits, all at twice the T-Display size.

Run: python tools/gen_fonts.py"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ASCII = "".join(chr(c) for c in range(0x20, 0x7F))
DIGITS = "+-0123456789dB%"


def render(name, chars, size, stroke):
    font = ImageFont.load_default(size=size)
    rendered = []
    for ch in chars:
        l, t, r, b = font.getbbox(ch, stroke_width=stroke)
        adv = int(round(font.getlength(ch))) + 2 * stroke + (1 if size > 20 else 0)
        w = max(1, r - l)
        asc, desc = font.getmetrics()
        img = Image.new("L", (w, asc + desc + 2 * stroke + 2), 0)
        ImageDraw.Draw(img).text((-l, stroke), ch, font=font, fill=255,
                                 stroke_width=stroke, stroke_fill=255)
        rendered.append((ch, w, l, adv, img))
    # Crop the rows no glyph uses.
    boxes = [img.getbbox() for *_, img in rendered if img.getbbox()]
    top = min(b[1] for b in boxes)
    bottom = max(b[3] for b in boxes)
    out, table = [], []
    for i, (ch, w, l, adv, img) in enumerate(rendered):
        img = img.crop((0, top, w, bottom))
        px = list(img.getdata())
        data = []
        for j in range(0, len(px), 2):
            a = px[j] >> 4
            bb = (px[j + 1] >> 4) if j + 1 < len(px) else 0
            data.append(a << 4 | bb)
        out.append("static const uint8_t %s_%d[] = {%s};" % (name, i, ",".join(map(str, data))))
        c = "'\\\\'" if ch == "\\" else "'\\''" if ch == "'" else "'%s'" % ch
        table.append("    {%s, %d, %d, %d, %s_%d}," % (c, w, l, adv, name, i))
    out.append("static const aaglyph_t %s_glyphs[] = {" % name)
    out += table
    out.append("};")
    out.append("static const aafont_t %s = {%s_glyphs, %d, %d};" % (name, name, len(chars), bottom - top))
    return out


lines = [
    "/* Generated by tools/gen_fonts.py: Aileron Regular (CC0), 4-bit alpha, two",
    " * pixels per byte (high nibble first), rows of `w` pixels; `x` is the",
    " * glyph's offset from the pen, `adv` the pen advance. */",
    "#pragma once", "#include <stdint.h>", "",
    "typedef struct { char ch; uint8_t w; int8_t x; uint8_t adv; const uint8_t *a; } aaglyph_t;",
    "typedef struct { const aaglyph_t *g; uint16_t n; uint8_t h; } aafont_t;", "",
    "#if UI_SCALE == 1",
]
lines += render("aa_big", DIGITS, 30, 1)
lines += ["#else"]
lines += render("aa_txt1", ASCII, 17, 0)
lines += render("aa_txt2", ASCII, 34, 1)
lines += render("aa_big", DIGITS, 60, 2)
lines += ["#endif", ""]
dst = Path(__file__).resolve().parent.parent / "main/boards/common/aafont.h"
dst.write_text("\n".join(lines) + "\n")
print("wrote", dst, dst.stat().st_size, "bytes")
